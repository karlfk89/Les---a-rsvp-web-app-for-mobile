// Converts TeX hyphenation pattern files (hyph-utf8) into compact ES modules
// in app/vendor/hyphenation, keeping each file's copyright and licence notice.
//
//   node tools/build-hyphenation.mjs <directory with the .tex files>
//
// The sources are in https://github.com/hyphenation/tex-hyphen, under
// hyph-utf8/tex/generic/hyph-utf8/patterns/tex/: hyph-no.tex, hyph-nb.tex,
// hyph-nn.tex and hyph-en-us.tex.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const source = process.argv[2];
if (!source) {
  console.error('Usage: node tools/build-hyphenation.mjs <directory with hyph-*.tex>');
  process.exit(2);
}

const read = (name) => readFileSync(join(source, name), 'utf8');

// The YAML-style header up to the first «% ====» line: title, copyright, licence.
const header = (tex) => tex.split('\n').filter((line) => line.startsWith('%'))
  .slice(0, tex.split('\n').findIndex((line) => line.startsWith('% ====')))
  .map((line) => `//${line.slice(1)}`)
  .join('\n');

function block(tex, command) {
  const start = tex.indexOf(`\\${command}{`);
  if (start < 0) return [];
  const end = tex.indexOf('}', start);
  return tex.slice(start + command.length + 2, end)
    .split('\n')
    .map((line) => line.replace(/%.*$/, '').trim())
    .flatMap((line) => line.split(/\s+/))
    .filter(Boolean);
}

function hyphenmins(tex) {
  const left = /typesetting:\s*\n%\s*left:\s*(\d+)\s*\n%\s*right:\s*(\d+)/.exec(tex);
  return left ? { leftMin: Number(left[1]), rightMin: Number(left[2]) } : { leftMin: 2, rightMin: 2 };
}

function writeModule(name, sources, data) {
  const out = join(root, 'app', 'vendor', 'hyphenation', `${name}.js`);
  mkdirSync(dirname(out), { recursive: true });
  const notices = sources.map(([file, tex]) => `// From ${file}:\n${header(tex)}`).join('\n//\n');
  writeFileSync(out, `// Generated by tools/build-hyphenation.mjs. Do not edit.\n${notices}\n\n` +
    `export default ${JSON.stringify(data, null, 0)};\n`);
  console.log(`${out}: ${data.patterns.split(' ').length} patterns`);
}

const no = read('hyph-no.tex');
const nb = read('hyph-nb.tex');
const nn = read('hyph-nn.tex');
writeModule('no', [['hyph-no.tex', no], ['hyph-nb.tex', nb], ['hyph-nn.tex', nn]], {
  ...hyphenmins(no),
  patterns: block(no, 'patterns').join(' '),
  exceptions: {
    nb: [...block(no, 'hyphenation'), ...block(nb, 'hyphenation')].join(' '),
    nn: [...block(no, 'hyphenation'), ...block(nn, 'hyphenation')].join(' '),
  },
});

const en = read('hyph-en-us.tex');
writeModule('en', [['hyph-en-us.tex', en]], {
  ...hyphenmins(en),
  patterns: block(en, 'patterns').join(' '),
  exceptions: { en: block(en, 'hyphenation').join(' ') },
});
